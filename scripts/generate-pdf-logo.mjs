import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync, inflateSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceFile = join(root, "public", "assets", "logo", "rac-logo.png");
const outputFile = join(root, "lib", "quotations", "rac-logo-pdf.ts");

function paeth(left, above, upperLeft) {
  const prediction = left + above - upperLeft;
  const leftDistance = Math.abs(prediction - left);
  const aboveDistance = Math.abs(prediction - above);
  const upperLeftDistance = Math.abs(prediction - upperLeft);
  return leftDistance <= aboveDistance && leftDistance <= upperLeftDistance
    ? left
    : aboveDistance <= upperLeftDistance
      ? above
      : upperLeft;
}

function readRgbPng(file) {
  const bytes = readFileSync(file);
  if (bytes.subarray(0, 8).compare(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])) !== 0) {
    throw new Error("The RAC logo must be a PNG file.");
  }

  let offset = 8;
  let width = 0;
  let height = 0;
  let bitDepth = 0;
  let colorType = 0;
  const idat = [];

  while (offset + 12 <= bytes.length) {
    const length = bytes.readUInt32BE(offset);
    const type = bytes.subarray(offset + 4, offset + 8).toString("ascii");
    const dataStart = offset + 8;
    const dataEnd = dataStart + length;
    if (dataEnd + 4 > bytes.length) throw new Error("Invalid RAC logo PNG.");

    if (type === "IHDR") {
      width = bytes.readUInt32BE(dataStart);
      height = bytes.readUInt32BE(dataStart + 4);
      bitDepth = bytes[dataStart + 8];
      colorType = bytes[dataStart + 9];
    } else if (type === "IDAT") {
      idat.push(bytes.subarray(dataStart, dataEnd));
    } else if (type === "IEND") {
      break;
    }
    offset = dataEnd + 4;
  }

  if (!width || !height || bitDepth !== 8 || colorType !== 2 || idat.length === 0) {
    throw new Error("The RAC logo must be a non-interlaced 8-bit RGB PNG.");
  }

  const bytesPerRow = width * 3;
  const scanlines = inflateSync(Buffer.concat(idat));
  if (scanlines.length !== height * (bytesPerRow + 1)) throw new Error("Unexpected RAC logo scanline data.");

  const rgb = Buffer.alloc(width * height * 3);
  for (let row = 0; row < height; row += 1) {
    const sourceOffset = row * (bytesPerRow + 1);
    const filter = scanlines[sourceOffset];
    const targetOffset = row * bytesPerRow;
    for (let column = 0; column < bytesPerRow; column += 1) {
      const value = scanlines[sourceOffset + 1 + column];
      const left = column >= 3 ? rgb[targetOffset + column - 3] : 0;
      const above = row > 0 ? rgb[targetOffset - bytesPerRow + column] : 0;
      const upperLeft = row > 0 && column >= 3 ? rgb[targetOffset - bytesPerRow + column - 3] : 0;
      const reconstructed = filter === 0
        ? value
        : filter === 1
          ? (value + left) & 255
          : filter === 2
            ? (value + above) & 255
            : filter === 3
              ? (value + Math.floor((left + above) / 2)) & 255
              : filter === 4
                ? (value + paeth(left, above, upperLeft)) & 255
                : Number.NaN;
      if (Number.isNaN(reconstructed)) throw new Error(`Unsupported PNG filter ${filter}.`);
      rgb[targetOffset + column] = reconstructed;
    }
  }
  return { width, height, rgb };
}

function resizeCrop(source, crop, target) {
  const scanlines = Buffer.alloc(target.height * (target.width * 3 + 1));
  for (let targetY = 0; targetY < target.height; targetY += 1) {
    const rowOffset = targetY * (target.width * 3 + 1);
    scanlines[rowOffset] = 0;
    const sourceY = crop.top + Math.floor((targetY * crop.height) / target.height);
    for (let targetX = 0; targetX < target.width; targetX += 1) {
      const sourceX = crop.left + Math.floor((targetX * crop.width) / target.width);
      const sourceOffset = (sourceY * source.width + sourceX) * 3;
      const targetOffset = rowOffset + 1 + targetX * 3;
      source.rgb.copy(scanlines, targetOffset, sourceOffset, sourceOffset + 3);
    }
  }
  return scanlines;
}

const source = readRgbPng(sourceFile);
// Crop the supplied source logo's white margin, then create a compact RGB raster for PDF embedding.
const crop = { left: 160, top: 300, width: 1150, height: 470 };
const target = { width: 300, height: 123 };
const compressedScanlines = deflateSync(resizeCrop(source, crop, target), { level: 9 });
const generated = `// Generated by scripts/generate-pdf-logo.mjs from public/assets/logo/rac-logo.png.\n// Do not edit the base64 payload by hand; regenerate it when the source logo changes.\nexport const racPdfLogo = {\n  width: ${target.width},\n  height: ${target.height},\n  compressedScanlinesBase64: \"${compressedScanlines.toString("base64")}\",\n} as const;\n`;

writeFileSync(outputFile, generated, "utf8");
console.log(`Generated ${outputFile} (${compressedScanlines.length} compressed bytes).`);
